import { WorkerExecutionRequest, WorkerExecutionResult } from '@nexora/shared';
import { storageService } from '../storage/index.js';

export async function executeWritingWorker(
  req: WorkerExecutionRequest,
  onLog: (line: string) => Promise<void>
): Promise<WorkerExecutionResult> {
  await onLog(`[Writing] Starting drafting process for: "${req.stepTitle}"`);
  const format = req.parameters.format || 'script';
  const topic = req.parameters.topic || req.taskTitle;

  await onLog(`[Writing] Analyzing tone, structure, and pacing requirements...`);
  await new Promise((r) => setTimeout(r, 800));

  await onLog(`[Writing] Drafting content outline and hooks...`);
  await new Promise((r) => setTimeout(r, 1000));

  let content = '';
  let filename = '';

  if (format === 'script' || req.taskTitle.toLowerCase().includes('script')) {
    filename = `youtube-script-${Date.now()}.md`;
    content = `# YouTube Video Script: ${topic}
**Duration:** ~5 Minutes | **Tone:** Engaging, High-Retention, Informative

---

### [00:00 - 00:30] Hook & Intro
**(Visual: Fast cuts, highlighted terminal logs, dynamic agent interface)**
**Host (VO):**
"What if your AI didn't just give you advice, but actually did the work while your laptop was completely closed? Today, we're testing Nexora AI — the autonomous cloud desktop agent."

---

### [00:30 - 01:45] The Problem with Traditional Chatbots
**(Visual: Side-by-side comparison of static chatbots vs cloud persistent workers)**
**Host (VO):**
"Most AI tools are tethered to your browser tab. The moment you close your laptop, the task stops. Nexora AI runs directly on persistent cloud workers. That means you can delegate tasks, walk away, and come back to completed results."

---

### [01:45 - 03:30] Live Delegation & Autonomous Execution
**(Visual: Live Activity view showing browser automation, terminal execution, and screenshots)**
**Host (VO):**
"Watch this: We gave it a single natural language command. It analyzed the intent, broke it down into subtasks, and assigned them to specialized cloud workers. Notice how every browser action and terminal command is streamed live with verified proof."

---

### [03:30 - 04:30] Security & Human-in-the-Loop Controls
**(Visual: Action approval modal highlighting risk score and user verification)**
**Host (VO):**
"Autonomy without safety is dangerous. Nexora AI includes strict approval gates for any consequential actions — like deleting files or publishing live content. You stay in full control."

---

### [04:30 - 05:00] Conclusion & Call to Action
**Host (VO):**
"Check out the link in the description to deploy Nexora AI on your own cloud instance. Hit like, subscribe, and tell me in the comments what task you want an autonomous agent to handle next!"

---

## Suggested YouTube Metadata
- **Title 1:** I Built an Autonomous Cloud AI Agent (It Works While My Laptop is Closed!)
- **Title 2:** The Future of AI Agents: Hands-On with Nexora AI
- **Title 3:** Why Chatbots Are Dead: Meet the Cloud Desktop Agent
- **Tags:** #AI #Agents #NexoraAI #CloudWorker #Automation #Gemini #Productivity
`;
  } else {
    filename = `article-${Date.now()}.md`;
    content = `# ${topic}

## Introduction
Autonomous cloud desktop agents represent a monumental paradigm shift in human-computer collaboration. Rather than relying on synchronous local interactions, decoupled cloud orchestrators empower users to delegate complex workflows effortlessly.

## Practical Implementation & Results
By pairing Google's Gemini reasoning capabilities with durable task queues (BullMQ/Redis) and isolated container workers, the system achieves remarkable fault resilience and true asynchronous execution.

## Summary
The future of work is not waiting on AI completions — it is reviewing verified artifacts generated by autonomous agents always working on your behalf.
`;
  }

  await onLog(`[Writing] Generating formatted document and titles...`);
  await new Promise((r) => setTimeout(r, 900));

  const artifact = await storageService.saveText(content, filename, {
    taskId: req.taskId,
    stepId: req.stepId,
    type: 'document',
    mimeType: 'text/markdown',
  });

  await onLog(`[Writing] Output written successfully to artifact: ${artifact.name}`);

  return {
    success: true,
    logs: [
      `Generated full structured ${format} content.`,
      `Saved document as ${artifact.name}`,
    ],
    outputData: {
      format,
      artifactUrl: artifact.url,
      wordCount: content.split(/\s+/).length,
      titleSuggestions: [
        'I Built an Autonomous Cloud AI Agent (It Works While My Laptop is Closed!)',
        'The Future of AI Agents: Hands-On with Nexora AI',
        'Why Chatbots Are Dead: Meet the Cloud Desktop Agent',
      ],
    },
    artifacts: [
      {
        name: artifact.name,
        type: 'document',
        path: artifact.path,
        mimeType: 'text/markdown',
      },
    ],
  };
}
